import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { nextVoiceReply, readVoiceReply, speechErrorLine, spokenCommand, voiceFriendly, voiceReplyLabel, voiceReplyShows, voiceReplySpeaks } from '../js/local-ai-panel.mjs';

test('voice replies spell minutes, speed, and steps', () => {
  const line = voiceFriendly('Ready to log on IdidIt: Walk, 30 min.\n1) Press Send again or tap Confirm to open the filled-in draft.\n2) Check the activity and minutes.');
  assert.match(line, /30 minutes/);
  assert.equal(/\bmin\b/.test(line), false);
  assert.match(line, /Step one\./);
  assert.match(line, /Step two\./);
  assert.equal(voiceFriendly('3mph'), '3 miles per hour');
  assert.equal(spokenCommand('confirm'), 'confirm');
  assert.equal(spokenCommand('Yes.'), 'confirm');
  assert.equal(spokenCommand('send'), 'confirm');
  assert.equal(spokenCommand('cancel'), 'cancel');
  assert.equal(spokenCommand('undo'), 'undo');
  assert.equal(spokenCommand('Walked 30 min'), '');
  const panel = readFileSync(new URL('../js/local-ai-panel.mjs', import.meta.url), 'utf8');
  assert.equal(panel.includes('speechSynthesis'), true);
  assert.equal(panel.includes('processLocally = true'), true);
  assert.equal(panel.includes('id="ai-speaking"'), true);
  assert.equal(panel.includes('id="ai-voice-mode"'), true);
  assert.equal(panel.includes('id="ai-mic-btn"'), true);
  assert.equal(panel.includes('id="ai-mic-btn" class="ai-detail"'), false);
  assert.equal(panel.includes("querySelector('#ai-mic-btn').addEventListener('click', () => startListen())"), true);
  assert.equal(panel.includes('heard.start()'), true);
  assert.equal(panel.includes('interimResults = true'), true);
  assert.equal(panel.includes('navigator.language'), true);
  assert.equal(panel.includes('getUserMedia'), false);
  assert.equal(panel.includes('is-listening'), true);
  assert.equal(panel.includes('aria-pressed'), true);
  assert.equal(panel.includes('if (!aiOn()) return'), false);
  assert.equal(panel.includes('Listening…'), true);
  assert.equal(/if \(!\('processLocally' in heard\)\) \{\s*showReply/.test(panel), false);
  assert.equal(speechErrorLine('not-allowed'), 'Mic blocked: allow microphone in site settings');
  assert.equal(speechErrorLine('no-speech').includes('No speech heard'), true);
  assert.equal(speechErrorLine('network').includes('connection'), true);
  assert.equal(speechErrorLine('audio-capture').includes('No microphone'), true);
  assert.equal(readFileSync(new URL('../vercel.json', import.meta.url), 'utf8').includes('microphone=(self)'), true);
  assert.equal(panel.includes('>Stop<'), true);
  assert.equal(panel.includes('>Listening<'), true);
  assert.equal(voiceReplyLabel('speak'), 'Speak and show');
  assert.equal(voiceReplyLabel('show'), 'Show only');
  assert.equal(voiceReplyLabel('off'), 'Off');
  assert.equal(nextVoiceReply('speak'), 'show');
  assert.equal(nextVoiceReply('show'), 'off');
  assert.equal(nextVoiceReply('off'), 'speak');
  assert.equal(voiceReplyShows('speak', true), true);
  assert.equal(voiceReplyShows('show', true), true);
  assert.equal(voiceReplyShows('off', true), false);
  assert.equal(voiceReplyShows('speak', false), false);
  assert.equal(voiceReplySpeaks('speak', true), true);
  assert.equal(voiceReplySpeaks('show', true), false);
  assert.equal(voiceReplySpeaks('off', true), false);
  const memory = new Map();
  const storage = { getItem: (key) => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
  assert.equal(readVoiceReply(storage), 'speak');
  storage.setItem('lgme.voice.read', 'off');
  assert.equal(readVoiceReply(storage), 'show');
  storage.setItem('lgme.voice.reply', 'off');
  assert.equal(readVoiceReply(storage), 'off');
  const gym = readFileSync(new URL('../js/gym-app.mjs', import.meta.url), 'utf8');
  assert.equal(gym.includes('id: \'voice-reply-settings\''), true);
  assert.equal(gym.includes('id: \'voice-reply-toggle\''), true);
  assert.equal(gym.includes('Speak and show, Show only, or Off.'), true);
});
