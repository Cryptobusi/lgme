import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as sim from '../js/p2p-exchange-sim.mjs';
import { CLARIFICATIONS, COVENANT_TITLE, acceptsCovenant, canonicalSigned, circleGate, covenantHash, covenantSections, exitReceipt, publicCovenant, signSponsor, sponsorStatus, velocityNote } from '../js/covenant.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const text = readFileSync(join(root, 'data/member-covenant.txt'), 'utf8');

test('the committed covenant file is the charter text', () => {
  const lines = text.replace(/\n$/, '').split('\n');
  assert.equal(lines[0], 'MEMBER COVENANT & MUTUAL CREDIT CHARTER');
  assert.equal(lines[1], 'Circle Name: Egonomic Mutual Clearing Circle');
  assert.equal(lines[2], 'Platform Reference: lgme.app / Sovereign Provenance Protocol');
  assert.equal(lines[3], 'Effective Date: November 10, 2026');
  assert.equal(lines[4], 'Preamble & Operating Stance');
  assert.equal(lines[8], 'Article 1 (Functional Need): Credits shall be drawn solely to satisfy immediate, real-world personal or household needs. Speculative purchasing, resale arbitrage, and balance hoarding are prohibited.');
  assert.equal(lines[11], 'Article 4 (Hard Credit Limits): Negative balances are hard-capped at an initial threshold of -50 credit units (maximum -200 upon community review). When the limit is reached, outbound debits suspend until counter-services restore the balance.');
  assert.equal(lines[18], 'Article 11 (Velocity Over Hoarding): Surplus positive balances must be spent back into fellow members\u2019 offerings within a 90-day window rather than held idle as claims over the community.');
  assert.equal(lines[19], 'Article 12 (Zero External Debt): The Circle remains completely unencumbered by outside bank debt, fiat collateral, or external liens. Member claims exist strictly within peer ledgers.');
  assert.equal(lines[22], ' * Primary Offering: ____');
  assert.equal(lines[23], ' * Secondary Offering: ____');
  assert.equal(lines[28], 'Member Legal Name: ____');
  assert.equal(lines[29], 'Signature: ____ Date: ____');
  assert.equal(lines[30], 'Sponsor 1 Signature: ____ Date: ____');
  assert.equal(lines[31], 'Sponsor 2 Signature: ____ Date: ____');
  assert.equal(lines[32], '(Original signed copy remains recorded locally and anchored to the community state register.)');
  assert.equal(lines.length, 33);
  assert.equal(text.split('____').length - 1, 9);
  assert.equal(text.includes('CONTENT_FROM_FILE'), false);
  const sections = covenantSections(text);
  assert.equal(sections.preamble.startsWith('MEMBER COVENANT'), true);
  assert.equal(sections.articles.includes('Article 1'), true);
  assert.equal(sections.articles.includes('Article 12'), true);
  assert.equal(sections.section2.startsWith('Section 2:'), true);
  assert.equal(COVENANT_TITLE, 'How this applies in the Health community (draft clarifications, pending owner approval)');
  assert.equal(CLARIFICATIONS.length, 13);
  assert.equal(CLARIFICATIONS[8].startsWith('Fitness coaching/personal training'), true);
  assert.equal(CLARIFICATIONS[11], 'If only one offering passes, the member gets Tier-0 rather than rejection.');
  assert.equal(text.includes(COVENANT_TITLE), false);
});

test('the covenant hash omits the legal name and credit stays closed until two sponsors sign', async () => {
  const base = { text, handle: 'ada', date: '2026-11-10', sponsors: [] };
  const plain = canonicalSigned(base);
  const named = canonicalSigned({ ...base, legalName: 'Ada Lovelace', signature: 'Ada Lovelace' });
  assert.equal(plain, named);
  assert.equal(plain.includes('Lovelace'), false);
  assert.equal(await covenantHash(base), await covenantHash({ ...base, legalName: 'Ada Lovelace' }));
  const one = signSponsor({ handle: 'ada', sponsors: [], token: 'abc' }, 'bo');
  assert.equal(sponsorStatus(one.record), 'Sponsors: 1. At least 2, including one from your group.');
  const two = signSponsor(one.record, 'cy', { at: '2026-11-10', inGroup: true });
  assert.equal(two.record.sponsors.length, 2);
  assert.equal(sponsorStatus(two.record), 'Sponsors: 2.');
  const three = signSponsor(two.record, 'dee');
  assert.equal(three.ok, true);
  assert.equal(three.record.sponsors.length, 3);
  assert.equal(publicCovenant({ ...two.record, legalName: 'Ada Lovelace' }).legalName, undefined);
  const store = sim.createMemoryStore();
  await sim.createPeer(store, { id: 'ada', name: 'Ada', balance: 12, floor: 0, creditLimit: -50, at: '2026-11-10T00:00:00.000Z' });
  const peer = await store.get('ada');
  peer.covenant = { handle: 'ada', sponsors: [] };
  await store.set('ada', peer);
  const listed = await sim.createListing(store, 'ada', {});
  const drawn = await sim.postDeed(store, 'ada', {});
  assert.equal(listed.error, 'Sponsors: 0. At least 2 sponsors, including one from your group.');
  assert.equal(drawn.error, listed.error);
  peer.covenant.sponsors = [{ handle: 'bo' }, { handle: 'cy' }];
  await store.set('ada', peer);
  assert.equal(circleGate(await store.get('ada'), 'credit').ok, false);
  peer.clubGroups = { dawn: { creator: 'bo' } };
  await store.set('ada', peer);
  assert.equal(circleGate(await store.get('ada'), 'credit').ok, true);
  const receipt = exitReceipt({ handle: 'ada', balance: 12, commitments: ['spot a session'], date: '2026-11-10' });
  assert.match(receipt, /Balance: 12.00/);
  assert.match(receipt, /spot a session/);
  assert.equal(velocityNote(12, '2026-08-01T00:00:00.000Z', Date.parse('2026-11-10T00:00:00.000Z')).includes('Nothing is taken automatically.'), true);
  assert.equal(velocityNote(12, '2026-11-01T00:00:00.000Z', Date.parse('2026-11-10T00:00:00.000Z')), '');
  assert.equal(acceptsCovenant({ handle: 'ada', token: '1234567890abcdef', date: '2026-11-10', hash: 'a'.repeat(64), legalName: 'Ada' }).ok, false);
});
